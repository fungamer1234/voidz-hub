		C.padding(card, 22, 22, 22, 22)
		local list = Instance.new("UIListLayout")
		list.SortOrder = Enum.SortOrder.LayoutOrder
		list.Padding = UDim.new(0, 10)
		list.Parent = card

		C.label(card, "VOIDZ HUB 2.0", { bold = true, size = 20, color = Theme.accentGlow, h = 26 })
		C.label(card, "Enter access key", { size = 12, color = Theme.textMuted, h = 18 })
		local box = C.input(card, "Key...")
		local status = C.label(card, "", { size = 11, color = Theme.danger, h = 16 })
		local function tryUnlock()
			local typed = string.upper(string.gsub(box.Text or "", "%s+", ""))
			if typed == KEY then
				State.unlocked = true
				gui:Destroy()
				onUnlock()
			else
				status.Text = "Invalid key"
				box.Text = ""
			end
		end
		C.button(card, "Unlock", tryUnlock, { w = 130, h = 36, accent = true })
		track(box.FocusLost:Connect(function(enter)
			if enter then
				tryUnlock()
			end
		end))
	end

	function Root.setVisible(vis)
		if Root.main then
			Root.main.Visible = vis == true
		end
		local sh = Root.gui and Root.gui:FindFirstChild("Shadow")
		if sh then
			sh.Visible = vis == true
		end
		State.hubOpen = vis == true
	end

	function Root.toggle()
		if not State.unlocked or not Root.main then
			return
		end
		Root.setVisible(not Root.main.Visible)
	end

	function Root.refreshPlayers()
		refreshPlayers()
	end

	function Root.mount()
		if Root.gui then
			return Root
		end
		local function openHub()
			buildMain()
			Notify.success("VOIDZ 2.0", "Loaded - pick a player on the right")
			Bus.emit("hub:ready")
		end
		if State.unlocked then
			openHub()
		else
			buildKeyGate(openHub)
		end
		track(Services.UserInputService.InputBegan:Connect(function(input, gp)
			if gp then
				return
			end
			if input.KeyCode == (State.keybinds.toggleHub or Enum.KeyCode.RightShift) then
				Root.toggle()
			end
		end))
		track(Bus.on("hub:unload", function()
			local g = (getgenv and getgenv()) or _G
			if type(g.VOIDZ_V3_UNLOAD) == "function" then
				g.VOIDZ_V3_UNLOAD()
			else
				Root.destroy()
			end
		end))
		track(Bus.on("player.selected", function()
			if Root._targetLab then
				Root._targetLab.Text = Select.label()
			end
			refreshPlayers()
		end))
		return Root
	end

	function Root.destroy()
		disconnectAll()
		if Root.gui then
			pcall(function()
				Root.gui:Destroy()
			end)
		end
		local parent = Util.getUiParent()
		for _, name in ipairs({ "VOIDZ_V3_Hub", "VOIDZ_V3_Key" }) do
			local g = parent:FindFirstChild(name)
			if g then
				pcall(function()
					g:Destroy()
				end)
			end
		end
		Notify.destroy()
		Root.gui, Root.main, Root.content, Root.playerList = nil, nil, nil, nil
		Root.navButtons = {}
		State.hubOpen = false
	end

	return Root
end
end)()

-- ===== module: init =====
__vz_modules["init"] = (function()
--[[ VOIDZ HUB 2.0 - entry ]]
return function(require)
	local State = require("core.state")
	local Bootstrap = require("core.bootstrap")
	local Bus = require("core.bus")
	local Loop = require("core.loop")
	local Config = require("core.config")
	local Root = require("ui.root")
	local Notify = require("ui.notify")
	local Gucci = require("systems.defense.gucci")
	local AntiGrab = require("systems.defense.anti_grab")
	local War = require("systems.defense.war")
	local Blobman = require("systems.grab.blobman")
	local Grab = require("systems.grab.core")
	local Kick = require("systems.combat.kick")
	local Actions = require("systems.combat.actions")
	local Aura = require("systems.combat.aura")
	local Loops = require("systems.combat.loops")
	local Anchor = require("systems.grab.anchor")
	local Toys = require("systems.object.toys")
	local Ownership = require("systems.object.ownership")
	local Chat = require("systems.utility.chat")
	local Visuals = require("systems.utility.visuals")
	local AntiAFK = require("systems.utility.antiafk")
	local Train = require("systems.world.train")

	local VOIDZ = {
		version = "2.0.0",
		phase = 5,
		Blobman = Blobman,
		Grab = Grab,
		Kick = Kick,
		Actions = Actions,
		Aura = Aura,
		Loops = Loops,
		Anchor = Anchor,
		Toys = Toys,
		Ownership = Ownership,
		Chat = Chat,
		Train = Train,
	}

	local function env()
		if type(getgenv) == "function" then
			local ok, g = pcall(getgenv)
			if ok and type(g) == "table" then
				return g
			end
		end
		return _G
	end

	local function unload()
		pcall(Config.save)
		pcall(function()
			State.setToggle("fly", false)
			State.setToggle("noclip", false)
			Train.drive(false)
		end)
		pcall(function()
			Anchor.destroy()
		end)
		pcall(function()
			Blobman.dismount()
		end)
		pcall(function()
			Grab.loopSelected(false)
			Grab.release()
		end)
		pcall(function()
			Kick.loop(false)
		end)
		pcall(function()
			Gucci.disable()
		end)
		pcall(function()
			AntiGrab.disable()
		end)
		pcall(function()
			War.disable()
		end)
		pcall(function()
			Root.destroy()
		end)
		pcall(function()
			Bootstrap.teardown()
		end)
		pcall(function()
			Notify.destroy()
		end)
		pcall(function()
			Loop.stopAll()
		end)
		local g = env()
		g.VOIDZ_V3 = nil
		g.VOIDZ_V3_UNLOAD = nil
		print("[VOIDZ] unloaded 2.0.0")
	end

	function VOIDZ.unload()
		unload()
	end

	function VOIDZ.bootstrap()
		local g = env()
		if type(g.VOIDZ_V3_UNLOAD) == "function" then
			pcall(g.VOIDZ_V3_UNLOAD)
		end

		State.phase = 5
		State.version = "2.0.0"
		VOIDZ.version = "2.0.0"

		Bootstrap.run()
		pcall(Ownership.resolve)

		pcall(Gucci.sync)
		pcall(AntiGrab.sync)
		pcall(War.sync)
		pcall(Blobman.sync)
		pcall(Anchor.sync)
		pcall(Aura.syncAll)
		pcall(Loops.syncAll)
		pcall(Visuals.sync)
		pcall(AntiAFK.sync)

		State.setToggle("fly", false)
		State.setToggle("noclip", false)
		State.setToggle("trainDrive", false)

		Root.mount()

		if State.getToggle("publicLoadChat") then
			pcall(Chat.announceLoadOnce)
		end

		g.VOIDZ_V3 = VOIDZ
		g.VOIDZ_V3_UNLOAD = unload
		g.VOIDZ_UNLOAD_V3 = unload

		Bus.on("toggle.gucci", function(v)
			if v then
				Gucci.enable()
			else
				Gucci.disable()
			end
		end)
		Bus.on("toggle.antiGrab", function(v)
			if v then
				AntiGrab.enable()
			else
				AntiGrab.disable()
			end
		end)
		Bus.on("toggle.warMode", function(v)
			if v then
				War.enable()
			else
				War.disable()
			end
		end)

		Bus.emit("voidz.ready", VOIDZ)
		print("[VOIDZ] 2.0.0 ready")
		return VOIDZ
	end

	return VOIDZ.bootstrap()
end
end)()


local __vz_ok, __vz_err = pcall(function()
