		Gucci.active = false
		Gucci._held = false
		Loop.stop("sys.gucci")
		Bus.emit("gucci.enabled", false)
	end

	function Gucci.sync()
		if State.getToggle("gucci") then
			Gucci.enable()
		else
			Gucci.disable()
		end
	end

