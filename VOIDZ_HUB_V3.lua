		if not r then
			Ownership.resolve()
			r = Services.FTAP.DestroyGrabLine
		end
		if not r then
			return false
		end
		return pcall(function()
			if r:IsA("RemoteEvent") then
				r:FireServer(part)
			elseif r:IsA("RemoteFunction") then
				r:InvokeServer(part)
			end
		end)
	end

