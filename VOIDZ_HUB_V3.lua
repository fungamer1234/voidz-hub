			Anchor.highlight = hl
		else
			local box = Instance.new("SelectionBox")
			box.Name = "VOIDZ_V3_AnchorBox"
			box.LineThickness = 0.05
			box.Color3 = Color3.fromRGB(140, 90, 255)
			box.Adornee = part
			box.Parent = part
			Anchor.box = box
		end
