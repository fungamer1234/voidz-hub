def strip_bom(text: str) -> str:
	if text.startswith("\ufeff"):
		return text[1:]
	return text


def to_ascii_safe(text: str) -> str:
	repl = {
		"\u2014": "-",
		"\u2013": "-",
		"\u2022": "*",
		"\u00b7": "*",
		"\u2026": "...",
		"\u00d7": "x",
		"\u2018": "'",
		"\u2019": "'",
		"\u201c": '"',
		"\u201d": '"',
		"\u00a0": " ",
	}
	for a, b in repl.items():
		text = text.replace(a, b)
	return "".join(ch if ord(ch) < 128 else "?" for ch in text)


def _lua_string(s: str) -> str:
	return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pack_module(name: str, source: str) -> str:
	source = to_ascii_safe(strip_bom(source)).rstrip() + "\n"
	if "return function" not in source:
		print(f"warning: {name} missing factory return", file=sys.stderr)
	return (
		f"__vz_modules[{_lua_string(name)}] = (function()\n"
		f"{source}"
		f"end)()\n"
	)


HEADER = r'''--[[
  VOIDZ HUB V3 - packed build
  BUILD: 2.0.0
  Generated by voidz_v3/build/pack.py - do not hand-edit.
  Key: VOIDZHUB
  Branch: v3
]]

-- Runtime shims (old executors / missing APIs)
do
	local _t = rawget(_G, "task")
	if type(_t) ~= "table" then
		_t = {}
		rawset(_G, "task", _t)
	end
	if type(_t.wait) ~= "function" then
		_t.wait = function(n)
			n = tonumber(n) or 0
			local t0 = os.clock()
			while os.clock() - t0 < n do end
		end
	end
	if type(_t.spawn) ~= "function" then
		_t.spawn = function(fn, ...)
			local a = { ... }
			coroutine.resume(coroutine.create(function()
				fn(unpack(a))
			end))
		end
	end
	if type(_t.delay) ~= "function" then
		_t.delay = function(d, fn, ...)
			local a = { ... }
			_t.spawn(function()
				_t.wait(d)
				fn(unpack(a))
			end)
		end
	end
	if type(_t.defer) ~= "function" then
		_t.defer = _t.spawn
	end
	if type(rawget(_G, "typeof")) ~= "function" then
		rawset(_G, "typeof", function(v)
			local ty = type(v)
			if ty == "userdata" then
				local ok, r = pcall(function()
					return v.ClassName
				end)
				if ok and r then
					return "Instance"
				end
				return "userdata"
			end
			return ty
		end)
	end
end

local __vz_modules = {}
local __vz_cache = {}
local __vz_loading = {}

local function __vz_require(name)
	name = string.gsub(tostring(name or ""), "/", ".")
	local cached = __vz_cache[name]
	if cached ~= nil then
		return cached
	end
	if __vz_loading[name] then
		error("[VOIDZ V3] circular require: " .. name, 2)
	end
	local factory = __vz_modules[name]
	if type(factory) ~= "function" then
		error("[VOIDZ V3] module not found: " .. tostring(name), 2)
	end
	__vz_loading[name] = true
	local ok, result = pcall(factory, __vz_require)
	__vz_loading[name] = nil
	if not ok then
		error("[VOIDZ V3] require failed: " .. tostring(name) .. " :: " .. tostring(result), 2)
	end
	if result == nil then
		error("[VOIDZ V3] module returned nil: " .. tostring(name), 2)
	end
	__vz_cache[name] = result
	return result
end

'''

FOOTER = r'''
local __vz_ok, __vz_err = pcall(function()
	__vz_require("init")
end)
if not __vz_ok then
	warn("[VOIDZ V3] boot failed: " .. tostring(__vz_err))
end
return __vz_ok
'''


def main() -> int:
	parts: list[str] = [HEADER]
	missing: list[str] = []
	for name, rel in MODULES:
		path = ROOT / rel
		if not path.is_file():
			missing.append(rel)
			continue
		parts.append(f"-- ===== module: {name} =====\n")
		parts.append(pack_module(name, path.read_text(encoding="utf-8")))
		parts.append("\n")
	if missing:
		print("ERROR missing:", missing, file=sys.stderr)
		return 1
	parts.append(FOOTER)
	OUT.write_text(to_ascii_safe("".join(parts)), encoding="utf-8")
	print(f"packed {len(MODULES)} modules -> {OUT} ({OUT.stat().st_size} bytes)")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
