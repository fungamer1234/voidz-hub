		_replaceTimes = {}, -- clock stamps
		_lastName = nil,
		_lastCf = nil,
		_lastToyName = nil,
	}

	local MAX_REPLACE_PER_10S = 4

	local function clearVisuals()
		if Anchor.highlight then
			pcall(function()
				Anchor.highlight:Destroy()
			end)
			Anchor.highlight = nil
		end
		if Anchor.box then
			pcall(function()
				Anchor.box:Destroy()
			end)
			Anchor.box = nil
