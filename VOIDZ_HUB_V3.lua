					end)
				end
				task.wait(ph.wait)
			end
		else
			-- default phoenix-like
			r = Util.rootOf(player)
			if r then
				Ownership.sno(r)
				skyVel(r)
				applyVel(r, power(), 1)
			end
		end

		restoreHome(home)
		if not quiet then
			Bus.emit("kick.done", player, ktype)
		end
		return true
	end

