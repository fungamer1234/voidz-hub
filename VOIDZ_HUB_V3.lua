		local cam = workspace.CurrentCamera
		local t = p and p.Character
		if cam and t then
			cam.CameraSubject = t:FindFirstChildOfClass("Humanoid") or t
			return true
		end
		return false
	end

	function Actions.unspectate()
		local cam = workspace.CurrentCamera
		local h = Util.hum()
		if cam and h then
			cam.CameraSubject = h
			return true
		end
		return false
	end

	function Actions.sky(p)
		if not Util.validP(p) then
			return false
		end
		local home = homeCF()
		visit(p, 25, function(r)
			skyVel(r)
			applyVel(r, power(), 2)
		end)
		restore(home)
		return true
	end

